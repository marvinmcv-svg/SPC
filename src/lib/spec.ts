import { scenes } from "@/content/systems";
import { getProduct } from "@/content/products";

export interface SpecAnswers {
  scene: string;
  zone: string;
  substrate: string;
  surfacePrep: string;
  serviceTempC: number;
  immersion: "none" | "water" | "potable" | "hydrocarbon" | "chemical" | "soil";
  standards: string[];
  method: "brush" | "spray" | "plural-spray";
  projectName: string;
}

export function recommend(a: SpecAnswers) {
  const scene = scenes.find((s) => s.id === a.scene) ?? scenes[0];
  const zone = scene.zones.find((z) => z.id === a.zone) ?? scene.zones[0];
  const products = [...zone.products];
  const notes: string[] = [];
  if (a.immersion === "chemical" || a.serviceTempC > 80) {
    if (!products.includes("epoxy-novolac-tank-lining")) products.push("epoxy-novolac-tank-lining");
    notes.push("Chemical immersion or elevated temperature: an epoxy novolac may be required. SPC technical service to confirm.");
  }
  if (a.immersion === "potable") notes.push("Potable water contact: every product in the system must hold the approval required in your jurisdiction.");
  if (a.serviceTempC < 0) notes.push("Sub-zero service: confirm low-temperature performance with technical service.");
  return { scene, zone, products: products.map((s) => getProduct(s)).filter((p) => p !== undefined), notes };
}

/** Generate editable specification text (CSI-style outline). */
export function specText(a: SpecAnswers) {
  const r = recommend(a);
  const lines = [
    `PROTECTIVE COATING SPECIFICATION — ${a.projectName || "[Project name]"}`,
    `Asset / area: ${r.scene.name} — ${r.zone.label}`,
    "",
    "1. SCOPE",
    `1.1 This section covers surface preparation, application and inspection of the coating system for: ${r.zone.description}`,
    "",
    "2. REFERENCE STANDARDS",
    ...(a.standards.length ? a.standards.map((s, i) => `2.${i + 1} ${s}`) : ["2.1 [Project standards to be listed]"]),
    "",
    "3. MATERIALS",
    ...r.products.map((p, i) => `3.${i + 1} ${p.name} (Specialty Polymer Coatings, Inc.) — 100% solids, zero VOC.${p.verified ? "" : " [Product to be confirmed by SPC]"}`),
    "3.x Substitutions require written approval and equivalent test data.",
    "",
    "4. SURFACE PREPARATION",
    `4.1 Substrate: ${a.substrate}.`,
    `4.2 Preparation: ${a.surfacePrep}. Remove all oil, grease and soluble salts before blasting.`,
    "4.3 Coat prepared surfaces before any flash rust or contamination occurs.",
    "",
    "5. APPLICATION",
    `5.1 Method: ${a.method === "plural-spray" ? "plural-component spray" : a.method}, per the manufacturer's current product data sheet.`,
    `5.2 Dry film thickness: ${r.zone.dft}.`,
    "5.3 Do not apply when steel temperature is less than 3 °C (5 °F) above the dew point, or outside the PDS temperature limits.",
    `5.4 Service conditions: ${a.serviceTempC} °C, ${a.immersion === "none" ? "atmospheric" : a.immersion + " exposure"}.`,
    "",
    "6. INSPECTION",
    "6.1 Measure DFT per SSPC-PA 2 / ISO 19840 or project requirement.",
    "6.2 Holiday test the full coated area at the voltage required by the project standard.",
    "6.3 Repair defects per the manufacturer's repair procedure.",
    "",
    "7. NOTES",
    ...(r.notes.length ? r.notes.map((n, i) => `7.${i + 1} ${n}`) : ["7.1 None."]),
    "",
    "This specification outline was generated by the SPC Spec Builder and must be reviewed by the project engineer and SPC technical service before use.",
  ];
  return lines.join("\n");
}
